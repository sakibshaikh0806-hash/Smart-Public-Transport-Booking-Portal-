// Fare Rates

const fareRates = {
    local: 20,
    bus: 15,
    express: 350,
    metro: 20,
    flight: 5000
};

let totalFare = 0;
let selectedPayment = "";


// Select Transport

function selectTransport(type) {

    document.getElementById("transportType").value = type;

    updateStations();

    document.getElementById("booking").scrollIntoView({
        behavior: "smooth"
    });
}


// Update Source and Destination Suggestions

function updateStations() {

    const type = document.getElementById("transportType").value;

    const sourceList = document.getElementById("sourceList");
    const destinationList = document.getElementById("destinationList");

    sourceList.innerHTML = "";
    destinationList.innerHTML = "";

    if (!type || !transportData[type]) {
        return;
    }

    transportData[type].forEach(place => {

        let sourceOption = document.createElement("option");
        sourceOption.value = place;
        sourceList.appendChild(sourceOption);

        let destinationOption = document.createElement("option");
        destinationOption.value = place;
        destinationList.appendChild(destinationOption);

    });
}


// Calculate Fare

function calculateFare() {

    const type = document.getElementById("transportType").value;
    const source = document.getElementById("source").value;
    const destination = document.getElementById("destination").value;
    const passengers = parseInt(document.getElementById("passengers").value);

    if (!type || !source || !destination) {

        alert("Please select transport, source and destination.");

        return;
    }

    if (source.toLowerCase() === destination.toLowerCase()) {

        alert("Source and destination cannot be same.");

        return;
    }

    if (!passengers || passengers < 1) {

        alert("Enter valid passenger count.");

        return;
    }

    let baseFare = fareRates[type];

    totalFare = baseFare * passengers;

    document.getElementById("fareBox").innerHTML =
        "Base Fare: ₹" + baseFare +
        "<br>Passengers: " + passengers +
        "<br><strong>Total Fare: ₹" + totalFare + "</strong>";
}


// Show Payment

function showPayment() {

    if (totalFare <= 0) {

        alert("Please calculate the fare first.");

        return;
    }

    document.getElementById("paymentSection")
        .classList.remove("hidden");

    document.getElementById("paymentSection")
        .scrollIntoView({
            behavior: "smooth"
        });
}


